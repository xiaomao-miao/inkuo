//! Minimal OOXML boilerplate shipped with every `.docx` package.
//!
//! Each constant is a verbatim OOXML payload that the writer injects
//! into the package alongside the freshly-built `word/document.xml`.
//! They're kept as separate `&str` constants (rather than baked into
//! `write_word_document`) for two reasons:
//!   1. The same blobs are reused by the tests, the in-app template
//!      picker, and a few external tools that splice the writer into
//!      a larger pipeline.
//!   2. Toggling any one of them off (e.g. to drop the `theme1.xml`
//!      part on an install that ships its own theme) is a one-line
//!      change instead of a code-dive into the package assembly.
//!
//! Pulled out of `mod.rs` (~340 lines of verbatim XML) so the
//! orchestrator stays focused on the dynamic payload.

